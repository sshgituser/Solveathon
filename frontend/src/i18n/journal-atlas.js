export function atlas(key) {
  const kk = L().code === "kk";
  const text = labels[key][kk ? 1 : 0];
  return kk ? text : text.replace(/(^|[\s(«])([ВвКкСсОоУуИиАаЯя])\s+(?=\S)/g, "$1$2\u00a0");
}
